import dotenv from 'dotenv';
dotenv.config();

import { AgentLLM } from './llm.js';
import { VaultClient } from './vault_client.js';
import { TransferProposal, ProposalValidationResult, ExecutionResult } from './types.js';

export class WardenAgentService {
  private llm: AgentLLM;
  private vaultClient: VaultClient;

  constructor() {
    this.llm = new AgentLLM();
    this.vaultClient = new VaultClient({
      networkId: process.env.NEAR_NETWORK_ID || 'testnet',
      nodeUrl: process.env.NEAR_NODE_URL || 'https://rpc.testnet.near.org',
      vaultContractId: process.env.VAULT_CONTRACT_ID || 'warden-vault.testnet',
      agentAccountId: process.env.AGENT_ACCOUNT_ID || 'warden-agent.testnet',
      agentPrivateKey: process.env.AGENT_PRIVATE_KEY || '',
    });
  }

  async init(): Promise<void> {
    await this.vaultClient.init();
  }

  /**
   * Phase 1: Propose
   * The AI LLM interprets the user instruction and produces a structured proposal.
   * Performs an advisory pre-check against the on-chain vault rules.
   */
  async createProposal(instruction: string): Promise<{
    proposal: TransferProposal;
    precheck: ProposalValidationResult;
  }> {
    const proposal = await this.llm.parseInstructionToProposal(instruction);

    // Advisory check against current vault state
    const errors: string[] = [];
    const warnings: string[] = [];
    let vaultState = undefined;

    try {
      vaultState = await this.vaultClient.getVaultInfo();

      if (vaultState.paused) {
        errors.push('Vault is currently PAUSED by the owner. No actions will execute.');
      }

      if (!vaultState.allowlist.includes(proposal.receiver_id)) {
        errors.push(
          `Recipient "${proposal.receiver_id}" is NOT in the on-chain allowlist. Execution will be rejected.`
        );
      }

      // Convert limits
      const yoctoMultiplier = 10n ** 24n;
      const amountYocto = BigInt(Math.floor(parseFloat(proposal.amount_near) * 1e6)) * (yoctoMultiplier / 1000000n);

      if (amountYocto > BigInt(vaultState.per_tx_limit)) {
        errors.push(
          `Amount exceeds per-tx limit of ${(Number(vaultState.per_tx_limit) / 1e24).toFixed(2)} NEAR.`
        );
      }

      const projectedDaily = BigInt(vaultState.spent_today) + amountYocto;
      if (projectedDaily > BigInt(vaultState.daily_limit)) {
        errors.push(
          `Amount would exceed 24h daily limit of ${(Number(vaultState.daily_limit) / 1e24).toFixed(2)} NEAR.`
        );
      }
    } catch (err: any) {
      warnings.push(`Could not fetch live vault state: ${err.message}. Relying on on-chain guardrails.`);
    }

    return {
      proposal,
      precheck: {
        valid: errors.length === 0,
        errors,
        warnings,
        vaultState,
      },
    };
  }

  /**
   * Phase 2: Confirm & Execute
   * Only called after human confirmation.
   * Submits the transaction to the vault using the restricted agent key.
   * If the LLM proposed an attack or rogue action, the vault contract rejects it on-chain.
   */
  async executeProposal(proposal: TransferProposal): Promise<ExecutionResult> {
    return this.vaultClient.executeProposal(proposal);
  }

  /**
   * Attack Demo Centerpiece:
   * Feeds a malicious prompt injection payload to the agent.
   * Demonstrates that even when the LLM is tricked into submitting an unauthorized drain,
   * the on-chain vault strictly rejects the action and preserves funds.
   */
  async simulateAttack(maliciousPrompt: string): Promise<{
    compromisedProposal: TransferProposal;
    executionResult: ExecutionResult;
  }> {
    console.log('\n--- [ATTACK SCENARIO INITIATED] ---');
    console.log(`Malicious Input:\n"${maliciousPrompt}"\n`);

    // 1. LLM processes malicious input
    const proposal = await this.llm.parseInstructionToProposal(maliciousPrompt);
    console.log('[Compromised Proposal Generated by LLM]:', JSON.stringify(proposal, null, 2));

    // 2. Submit to on-chain vault with agent key
    console.log('\nSubmitting proposal to Vault contract with restricted agent key...');
    const result = await this.vaultClient.executeProposal(proposal);

    if (!result.success) {
      console.log('>>> [ON-CHAIN VAULT SAFETY INTERVENTION]');
      console.log(`Status: REJECTED ON-CHAIN`);
      console.log(`Rejection Reason: ${result.rejectedEvent?.reason}`);
      console.log(`Vault Defense: Funds remain safe!`);
    } else {
      console.warn('WARNING: Action was unexpectedly executed!');
    }

    return {
      compromisedProposal: proposal,
      executionResult: result,
    };
  }
}

